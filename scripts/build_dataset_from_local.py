def load_scenic_spots() -> List[Dict]:
    """加载 MetaAgentsPaaS 项目的 scenic_spots.json"""
    src = Path(r"c:\Users\zhaoxi\Projects\MetaAgentsPaaS\db\data\scenic_spots.json")
    if not src.exists():
        return []
    with open(src, "r", encoding="utf-8") as f:
        return json.load(f)


def expand_scenic_data(spots: List[Dict]) -> List[Dict]:
    """把 5 个景点 × 8 模板扩展成 40 条问答数据"""
    data = []
    for spot in spots:
        for tpl in SCENIC_TEMPLATES:
            data.append({
                "instruction": tpl["instruction"].format(**spot),
                "input": "",
                "output": tpl["output_fmt"].format(**spot),
                "source": "scenic_template",
                "spot": spot["name"],
                "topic": tpl["topic"],
            })
    return data


