def main():
    dataset = build_dataset()
    out_path = Path("data/tourism_raw.json")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(dataset, f, ensure_ascii=False, indent=2)

    # 统计
    print(f"\n=== 数据集生成完成 ===")
    print(f"总数: {len(dataset)} 条")
    print(f"输出: {out_path.absolute()}")

    print(f"\n=== 数据来源分布 ===")
    from collections import Counter
    src_dist = Counter(d["source"] for d in dataset)
    for src, cnt in sorted(src_dist.items(), key=lambda x: -x[1]):
        print(f"  {src}: {cnt} 条 ({cnt/len(dataset)*100:.1f}%)")

    print(f"\n=== 景点分布 ===")
    spot_dist = Counter(d.get("spot", "未知") for d in dataset)
    for spot, cnt in sorted(spot_dist.items(), key=lambda x: -x[1])[:10]:
        print(f"  {spot}: {cnt} 条")

    # 长度统计
    lens = [len(d["output"]) for d in dataset]
    print(f"\n=== 输出长度 ===")
    print(f"  最短: {min(lens)} 字")
    print(f"  最长: {max(lens)} 字")
    print(f"  平均: {sum(lens)//len(lens)} 字")

    # 样例
    print(f"\n=== 样例（第1条）===")
    print(f"instruction: {dataset[0]['instruction']}")
    print(f"output: {dataset[0]['output'][:200]}...")


