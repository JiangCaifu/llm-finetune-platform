    expanded = expand_scenic_data(spots)
    print(f"[2/3] 模板扩展: {len(expanded)} 条数据")

    manual = MANUAL_DATA
    for i, item in enumerate(manual):
        item["source"] = "manual"
        item["spot"] = "通用"
        item["topic"] = "general"
    print(f"[3/3] 人工编写: {len(manual)} 条数据")

    dataset = expanded + manual
